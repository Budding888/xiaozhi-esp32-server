"""
医疗关键词配置

包含 _is_medical_query() 中用到的排除模式关键词表和医疗知识关键词表，
从 connection.py 抽取的独立模块。
"""

from typing import Optional

from config.logger import setup_logging

TAG = __name__
logger = setup_logging()

# ================================================================
# 排除模式：体征数据上报/记录/查询
# 当查询同时包含体征测量词和上报操作词时，判定为数据上报意图
# ================================================================
REPORTING_VERBS = frozenset({
    "上报", "提交", "登记", "报上去", "上交", "提交一下", "上报一下",
    "帮我提交", "帮我上报", "反馈一下",
    "记录", "录入", "保存", "记下来", "存一下", "帮我记下", "录入进去", "保存一下",
    "查询", "查一下", "查查", "检索", "查阅", "调取", "询查", "核验", "核对",
    "浏览", "查一查", "看一看", "找一找", "帮我查下", "翻一下", "搜一下", "看下记录",
})

MEASUREMENT_NOUNS = frozenset({
    "血压", "血糖", "体重", "尿量", "心率", "高压", "低压",
    "收缩压", "舒张压",
})

# ================================================================
# 排除模式：显式要求从知识库查询
# ================================================================
KNOWLEDGE_BASE_MARKERS = frozenset({
    "从知识库", "知识库查", "查知识库", "知识库检索", "知识库里有",
})

# ================================================================
# 医疗知识关键词
# ================================================================
MEDICAL_KEYWORDS = [
    # 腹透相关
    "腹透", "腹膜透析", "透析", "腹膜炎",
    "腹透液", "透析液", "出口感染", "管路",
    "换液", "换药", "碘伏帽",
    # 并发症
    "并发症", "感染", "发炎",
    # 饮食营养
    "饮食", "吃什么", "忌口", "食谱", "三餐",
    "营养", "蛋白质", "饮水量", "喝水", "水分",
    "钾", "磷", "钠", "盐",
    # 体征
    "血压", "血糖", "体重", "尿量", "水肿",
    "超滤", "干体重", "腹围",
    # 药物
    "吃药", "用药", "药物", "药", "禁忌",
    # 护理
    "护理", "注意", "怎么", "如何",
    # 症状
    "肚子痛", "腹痛", "发热", "发烧", "呕吐",
    "恶心", "头晕", "乏力", "肿胀",
]


def is_medical_query(query: str, logger_instance=None) -> bool:
    """
    通过关键词匹配检测是否为腹透医疗问题

    Args:
        query: 用户输入文本
        logger_instance: 可选的 logger，用于输出调试日志

    Returns:
        bool: 是否为医疗问题
    """
    if not query:
        return False

    log = logger_instance or logger

    # ================================================================
    # 排除模式1：体征数据上报/记录/查询
    # ================================================================
    has_reporting_verb = any(v in query for v in REPORTING_VERBS)
    has_measurement = any(n in query for n in MEASUREMENT_NOUNS)

    if has_reporting_verb and has_measurement:
        log.info(f"医疗预过滤器排除（体征数据上报/查询）: {query[:50]}")
        return False

    # ================================================================
    # 排除模式2：服药提醒更新
    # ================================================================
    if "更新" in query and ("提醒" in query or "服药" in query or "用药提醒" in query):
        log.info(f"医疗预过滤器排除（服药提醒更新）: {query[:50]}")
        return False

    # ================================================================
    # 排除模式3：显式要求从知识库查询
    # ================================================================
    if any(marker in query for marker in KNOWLEDGE_BASE_MARKERS):
        log.info(f"医疗预过滤器排除（显式知识库查询）: {query[:50]}")
        return False

    # ================================================================
    # 医疗知识关键词匹配
    # ================================================================
    query_lower = query.lower()
    for keyword in MEDICAL_KEYWORDS:
        if keyword in query_lower or keyword in query:
            log.debug(f"医疗关键词命中: '{keyword}' (query: {query[:30]}...)")
            return True

    return False
